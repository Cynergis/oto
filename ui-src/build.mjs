// Builds the workbench, the one built-in view, into oto/ui/workbench/. The explorer under ui-src/explorer/
// is the graph component the workbench mounts on its Knowledge page (and the pure modules the tests run
// under Node); it is no longer built as an app of its own. Run from ui-src/: `npm run build`.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const rfCss = readFileSync(join(here, "node_modules", "@xyflow", "react", "dist", "style.css"), "utf8");
const ours = readFileSync(join(here, "explorer", "explorer.css"), "utf8");

// The workbench (ui-src/workbench/) into oto/ui/workbench/: React, shadcn/ui and the explorer's graph in
// one bundle, no runtime network. Its CSS is Tailwind's output, then React Flow's base styles and the
// explorer's own, with the explorer's page-level rules dropped and its variables renamed --mx-*, so they
// sit beside shadcn's tokens without either taking over the other.
import { execFileSync } from "node:child_process";

const wbOut = join(here, "..", "oto", "ui", "workbench");
mkdirSync(wbOut, { recursive: true });
await build({
  entryPoints: [join(here, "workbench", "main.tsx")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2019"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  outfile: join(wbOut, "workbench.js"),
  legalComments: "none",
  logLevel: "info",
});
const tailwind = join(here, "node_modules", ".bin", "tailwindcss");
const twCss = join(here, "node_modules", ".workbench.tailwind.css");
execFileSync(tailwind, ["-i", join(here, "workbench", "styles.css"), "-o", twCss, "--minify"], { cwd: join(here, "workbench"), stdio: "inherit" });
const MX = ["accent-soft", "warn-soft", "derived-soft", "ground", "surface", "ink", "muted", "rule", "edge", "accent", "warn", "derived", "sans", "mono"];
const mxCss = ours
  .split("\n")
  .filter(line => !/^\s*(\*|html|body|code|#explorer|\.mx-top|\.mx-brand|\.mx-foot|\.mx-fresh)\b/.test(line))
  .join("\n")
  .replace(new RegExp("--(" + MX.join("|") + ")(?![\\w-])", "g"), "--mx-$1");
writeFileSync(join(wbOut, "workbench.css"),
  "/* Generated by ui-src/build.mjs: Tailwind with shadcn/ui's tokens, React Flow base styles (MIT), the explorer's styles. */\n"
  + readFileSync(twCss, "utf8") + "\n" + rfCss + "\n" + mxCss);
console.log("wrote", join(wbOut, "workbench.css"));
